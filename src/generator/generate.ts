const OWNER_HEADER =
  "// Generated by moeicons CLI. Do not edit manually; re-run `moeicons generate`.";

/**
 * Vanilla project top-level index re-exports each selected style group as a
 * namespace (`export * as MoeOutline from './moe-outline'`), mirroring the
 * code-library layer. Two style groups must therefore never map to the same
 * namespace identifier, and the namespace must not shadow the reserved
 * runtime/types exports.
 */
function reportVanillaNamespaceCollisions(config: MoeiconsConfigFile): string[] {
  const reserved = new Set(["createMoeiconsRuntime", "Theme", "VanillaIconOptions", "default"]);
  const seen = new Map<string, string>();
  const problems: string[] = [];
  const styleGroups = [...new Set(Object.values(config.themes).map((entry) => entry.styleGroup))];
  for (const styleGroup of styleGroups) {
    const ns = toProxyName(styleGroup);
    if (reserved.has(ns)) {
      problems.push(`vanilla style group "${styleGroup}" maps to reserved export "${ns}"`);
      continue;
    }
    const owner = seen.get(ns);
    if (owner) {
      problems.push(
        `vanilla style groups "${owner}" and "${styleGroup}" both map to namespace "${ns}"`,
      );
    } else {
      seen.set(ns, styleGroup);
    }
  }
  return problems;
}

function themeClassExpr(themes: readonly ResolvedTheme[]): string {
  const entries = themes
    .map((theme) => {
      const className = theme.entry.className;
      return `  ${JSON.stringify(theme.theme)}: ${className === undefined ? "undefined" : JSON.stringify(className)},`;
    })
    .join("\n");
  return `const themeClassName: Partial<Record<Theme, string | undefined>> = {\n${entries}\n};\n`;
}

function themeDefaultsExpr(themes: readonly ResolvedTheme[]): string {
  return `const themeDefaultSize: Record<Theme, number> = {\n${themes.map((theme) => `  ${JSON.stringify(theme.theme)}: ${theme.entry.defaultSize ?? 24},`).join("\n")}\n};\n` +
    `const themeStrokeWidth: Partial<Record<Theme, number>> = {\n${themes.map((theme) => `  ${JSON.stringify(theme.theme)}: ${theme.entry.strokeWidth === undefined ? "undefined" : theme.entry.strokeWidth},`).join("\n")}\n};\n`;
}

function installedIconImport(outputDir: string, target: "react" | "vue", group: string, iconId: string): string {
  const file = `${toProxyName(iconId)}${target === "vue" ? ".vue" : ""}.js`;
  const relative = posix.relative(outputDir.replace(/\/$/, ""), `.moeicons/artifact/${target}/${group}/${file}`);
  return relative.startsWith(".") ? relative : `./${relative}`;
}

function effectiveThemeForIcon(
  iconId: string,
  logical: ResolvedTheme,
  themes: readonly ResolvedTheme[],
  config: MoeiconsConfigFile,
  sourceCatalog: IconCatalog,
): ResolvedTheme {
  const icon = findCatalogIcon(iconId, sourceCatalog);
  if (icon?.availableIn.includes(logical.entry.styleGroup)) return logical;
  return themes.find((theme) => theme.theme === config.defaultTheme) ?? logical;
}


import type { MoeiconsConfigFile } from "../project/config.js";

/**
 * React/Vue proxy generation. Purely returns owned file paths/content for
 * types, registry, provider/plugin, proxies and barrel exports. Rejects
 * duplicate PascalCase names and missing fallback.
 */

export interface GeneratedFile {
  readonly path: string;
  readonly content: string;
}

export interface GenerationResult {
  readonly ok: true;
  readonly files: GeneratedFile[];
}

export interface GenerationError {
  readonly ok: false;
  readonly errors: string[];
}

export type GenerationOutcome = GenerationResult | GenerationError;

/** kebab → Pascal: `arrow-chevron-right` → `ArrowChevronRight`. */
export function toPascalCase(id: string): string {
  return id
    .split("-")
    .map((seg) => seg.charAt(0).toUpperCase() + seg.slice(1))
    .join("");
}

const OWNER_HEADER =
  "// Generated by moeicons CLI. Do not edit manually; re-run `moeicons generate`.";

/**
 * Plan generated files for a config. Returns only owned paths under the config
 * output dir. Rejects duplicate PascalCase names and a config with no themes.
 */
export function planGeneratedFiles(
  config: MoeiconsConfigFile,
  outputDir: string,
): GenerationOutcome {
  const errors: string[] = [];
  if (Object.keys(config.themes).length === 0) {
    errors.push("config has no themes");
  }
  if (config.icons.length === 0) {
    errors.push("config has no icons");
  }

  const seen = new Map<string, string>();
  for (const iconId of config.icons) {
    const pascal = toPascalCase(iconId);
    const existing = seen.get(pascal);
    if (existing) {
      errors.push(`duplicate PascalCase name "${pascal}" from "${existing}" and "${iconId}"`);
    } else {
      seen.set(pascal, iconId);
    }
  }
  if (errors.length > 0) return { ok: false, errors };

  const files: GeneratedFile[] = [];
  const rel = (p: string) => `${outputDir.replace(/\/$/, "")}/${p}`;

  files.push({
    path: rel("types.ts"),
    content: `${OWNER_HEADER}
export interface IconProps {
  className?: string;
  size?: number;
  strokeWidth?: number;
  "aria-label"?: string;
  [key: string]: unknown;
}
`,
  });

  files.push({
    path: rel("registry.ts"),
    content: `${OWNER_HEADER}
import type { IconProps } from "./types";

export type IconId =
${config.icons.map((id) => `  | "${id}"`).join("\n")};

export interface ThemeRegistry {
${config.icons.map((id) => `  readonly ${toPascalCase(id)}: (props: IconProps) => JSX.Element;`).join("\n")}
}

export const registry: Record<string, ThemeRegistry> = {
${Object.keys(config.themes)
  .map((theme) => {
    const entry = config.themes[theme];
    const styles = (entry?.styles ?? []).map((s) => `"${s}"`).join(", ");
    return `  "${theme}": { /* styles: ${styles} */ } as unknown as ThemeRegistry,`;
  })
  .join("\n")}
};
`,
  });

  for (const iconId of config.icons) {
    const pascal = toPascalCase(iconId);
    files.push({
      path: rel(`icons/${pascal}.tsx`),
      content: `${OWNER_HEADER}
import type { IconProps } from "../types";

export function ${pascal}(props: IconProps) {
  return <svg data-moeicon="${iconId}" data-theme="auto" {...props} />;
}
`,
    });
  }

  files.push({
    path: rel("index.ts"),
    content: `${OWNER_HEADER}
export type { IconProps } from "./types";
${config.icons.map((id) => `export { ${toPascalCase(id)} } from "./icons/${toPascalCase(id)}";`).join("\n")}
`,
  });

  return { ok: true, files };
}

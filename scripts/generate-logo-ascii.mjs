#!/usr/bin/env node
/**
 * Dev-only: rasterize an SVG logo to a 36x18 ASCII constant.
 * Runtime CLI never imports sharp. Output must not contain absolute paths.
 */
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, renameSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

export const MAX_COLS = 36;
export const MAX_ROWS = 18;
export const V_SCALE = 0.5;
export const LOGO_CHARS = Object.freeze([" ", ".", ":", "*", "#"]);

const TRANSPARENT_ALPHA = 16;
const WHITE_LUMA = 245;

export class LogoGenerateError extends Error {
  constructor(message) {
    super(message);
    this.name = "LogoGenerateError";
  }
}

export function parseArgv(argv) {
  const index = argv.indexOf("--input");
  if (index === -1 || argv[index + 1] === undefined || argv[index + 1].startsWith("--")) {
    throw new LogoGenerateError("--input is required");
  }
  return { input: argv[index + 1] };
}

/** Map one grayscale+alpha pixel to a gradient character. Light → `.`, dark → `#`. */
export function mapPixel(luma, alpha) {
  if (alpha < TRANSPARENT_ALPHA || luma >= WHITE_LUMA) return " ";
  if (luma < 64) return "#";
  if (luma < 128) return "*";
  if (luma < 192) return ":";
  return ".";
}

export function rasterToLines(pixels, width, height, channels) {
  const lines = [];
  for (let y = 0; y < height; y += 1) {
    let line = "";
    for (let x = 0; x < width; x += 1) {
      const offset = (y * width + x) * channels;
      const luma = pixels[offset] ?? 255;
      const alpha = channels >= 2 ? (pixels[offset + (channels - 1)] ?? 0) : 255;
      line += mapPixel(luma, alpha);
    }
    lines.push(line);
  }
  return lines;
}

export function trimAscii(lines) {
  if (lines.length === 0) return [];
  let top = 0;
  while (top < lines.length && lines[top].trim() === "") top += 1;
  let bottom = lines.length - 1;
  while (bottom >= top && lines[bottom].trim() === "") bottom -= 1;
  if (top > bottom) return [];
  const slice = lines.slice(top, bottom + 1);
  let left = Number.POSITIVE_INFINITY;
  let right = 0;
  for (const line of slice) {
    const first = line.search(/\S/);
    if (first === -1) continue;
    const last = line.length - 1 - [...line].reverse().join("").search(/\S/);
    left = Math.min(left, first);
    right = Math.max(right, last);
  }
  if (!Number.isFinite(left)) return [];
  return slice.map((line) => line.slice(left, right + 1));
}

function assertFits(lines) {
  const height = lines.length;
  const width = height === 0 ? 0 : Math.max(...lines.map((line) => line.length));
  if (width > MAX_COLS || height > MAX_ROWS) {
    throw new LogoGenerateError(`logo exceeds ${MAX_COLS}x${MAX_ROWS} after trim (${width}x${height})`);
  }
}

function renderSource(lines, meta) {
  const literalLines = lines.map((line) => JSON.stringify(line)).join(",\n  ");
  return [
    "/**",
    " * Generated by scripts/generate-logo-ascii.mjs. Do not edit by hand.",
    ` * source: ${meta.sourceName}`,
    ` * sha256: ${meta.sha256}`,
    ` * width: ${meta.width}`,
    ` * vscale: ${meta.vscale}`,
    ` * gradient: ${JSON.stringify(LOGO_CHARS.join(""))}`,
    " */",
    "export const MOEICONS_LOGO_ASCII = [",
    `  ${literalLines}`,
    "].join(\"\\n\");",
    "",
  ].join("\n");
}

export async function rasterizeSvg(inputBytes, width, height) {
  const { default: sharp } = await import("sharp");
  try {
    const { data, info } = await sharp(inputBytes, { density: 300 })
      .resize(width, height, { fit: "fill", kernel: "lanczos3" })
      .grayscale()
      .ensureAlpha()
      .raw()
      .toBuffer({ resolveWithObject: true });
    return { data, width: info.width, height: info.height, channels: info.channels };
  } catch (error) {
    throw new LogoGenerateError(
      `failed to decode SVG (${error instanceof Error ? error.message : String(error)})`,
    );
  }
}

export async function generateLogoAscii(options) {
  const inputPath = resolve(options.input);
  if (!existsSync(inputPath)) {
    throw new LogoGenerateError(`SVG not found: ${options.input}`);
  }
  const inputBytes = readFileSync(inputPath);
  const { default: sharp } = await import("sharp");
  let metadata;
  try {
    metadata = await sharp(inputBytes, { density: 300 }).metadata();
  } catch (error) {
    throw new LogoGenerateError(
      `failed to decode SVG (${error instanceof Error ? error.message : String(error)})`,
    );
  }
  const sourceWidth = metadata.width ?? 0;
  const sourceHeight = metadata.height ?? 0;
  if (sourceWidth < 1 || sourceHeight < 1) {
    throw new LogoGenerateError("failed to decode SVG (missing dimensions)");
  }
  const cols = MAX_COLS;
  const rows = Math.max(1, Math.round((sourceHeight / sourceWidth) * cols * V_SCALE));
  const raster = await rasterizeSvg(inputBytes, cols, rows);
  const lines = trimAscii(rasterToLines(raster.data, raster.width, raster.height, raster.channels));
  assertFits(lines);
  const source = renderSource(lines, {
    sourceName: basename(inputPath),
    sha256: createHash("sha256").update(inputBytes).digest("hex"),
    width: MAX_COLS,
    vscale: V_SCALE,
  });
  if (/\b(?:\/Users\/|\/home\/|[A-Za-z]:\\)/.test(source)) {
    throw new LogoGenerateError("generated output contained an absolute path");
  }
  mkdirSync(dirname(options.output), { recursive: true });
  const tempPath = `${options.output}.tmp`;
  writeFileSync(tempPath, source);
  renameSync(tempPath, options.output);
  return { lines, source };
}

async function main() {
  try {
    const { input } = parseArgv(process.argv.slice(2));
    const output = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "ui", "generated", "logo-ascii.ts");
    await generateLogoAscii({ input, output });
    process.stdout.write(`wrote ${output}\n`);
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    process.stderr.write(`error: ${message}\n`);
    process.exitCode = 1;
  }
}

const entry = process.argv[1] ? pathToFileURL(resolve(process.argv[1])).href : "";
if (import.meta.url === entry) {
  await main();
}
